#!/usr/bin/env node

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { deriveLocaleCapabilities, deriveLocaleMetadata } from '../dist/esm/locale-contract.js';
import LOCALES from '../dist/esm/locales/index.js';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repositoryRoot, 'docs/guide/locale-capabilities.md');
const dataOutputPath = path.join(repositoryRoot, 'src/locale-manifest-data.ts');

const entries = Object.keys(LOCALES)
  .sort()
  .map((localeCode) => {
    const config = new LOCALES[localeCode]().config;
    return {
      localeCode,
      capabilities: deriveLocaleCapabilities(config),
      metadata: deriveLocaleMetadata(config),
    };
  });

function renderTable(headers, rows) {
  const widths = headers.map((header, column) => Math.max(header.length, ...rows.map((row) => row[column].length)));
  const renderRow = (row) => `| ${row.map((value, column) => value.padEnd(widths[column])).join(' | ')} |`;

  return [renderRow(headers), renderRow(widths.map((width) => '-'.repeat(width))), ...rows.map(renderRow)];
}

function renderGender(capabilities) {
  if (capabilities.gender.cardinal && capabilities.gender.ordinal) {
    return 'Cardinal + ordinal';
  }
  if (capabilities.gender.cardinal) {
    return 'Cardinal';
  }
  if (capabilities.gender.ordinal) {
    return 'Ordinal';
  }
  return '—';
}

function renderFractionDigits(capabilities) {
  return capabilities.decimals.fraction ? capabilities.decimals.fractionDigits.join(', ') : '—';
}

function renderNumberingSystem(system) {
  return {
    'base-thousand': 'Base thousand',
    indian: 'Indian',
    'east-asian': 'East Asian',
    'locale-specific': 'Locale-specific',
  }[system];
}

function renderLargestMagnitude(range) {
  return range.largestNamedMagnitudeExponent === null
    ? range.largestNamedMagnitude
    : `10^${range.largestNamedMagnitudeExponent}`;
}

function renderMaximum(range) {
  const maximum = range.maximumSupported.cardinal;
  return /^9+$/.test(maximum) ? `10^${maximum.length} - 1` : maximum;
}

function renderDocument() {
  const count = (predicate) => entries.filter(predicate).length;
  const rows = entries.map(({ localeCode, capabilities, metadata }) => [
    `\`${localeCode}\``,
    renderNumberingSystem(metadata.numbering.system),
    renderLargestMagnitude(metadata.range),
    renderMaximum(metadata.range),
    capabilities.ordinal ? 'Yes' : 'No',
    renderGender(capabilities),
    capabilities.formal ? 'Yes' : 'No',
    renderFractionDigits(capabilities),
    String(capabilities.currencyPrecision),
  ]);

  return [
    '---',
    'title: Locale Capability Manifest | to-words',
    'description: Generated, machine-verifiable feature support for every to-words locale, including ordinals, gender, formal numerals, fractions, and currency precision.',
    '---',
    '',
    '# Locale Capability Manifest',
    '',
    '<!-- This file is generated by scripts/generate-locale-docs.mjs. Do not edit it directly. -->',
    '',
    'This reference is generated from the locale configurations shipped by the package. It is checked in CI, so the documentation and runtime manifest cannot silently drift apart.',
    '',
    `**${entries.length} locales** · **${count(({ capabilities }) => capabilities.ordinal)} ordinal** · **${count(({ capabilities }) => capabilities.decimals.fraction)} fraction style** · **${count(({ capabilities }) => capabilities.gender.cardinal)} cardinal gender** · **${count(({ capabilities }) => capabilities.gender.ordinal)} ordinal gender** · **${count(({ capabilities }) => capabilities.formal)} formal numeral locales**`,
    '',
    '## Programmatic Usage',
    '',
    '```ts',
    "import { getLocaleCapabilities, getLocaleMetadata, isSupportedLocale, LOCALE_MANIFEST } from 'to-words/manifest';",
    '',
    "isSupportedLocale('fr-FR'); // true",
    "getLocaleCapabilities('fr-FR')?.decimals.fraction; // true",
    "getLocaleMetadata('hi-IN')?.numbering.grouping; // [3, 2]",
    "getLocaleMetadata('en-US')?.range.largestNamedMagnitude; // exact decimal string",
    "getLocaleMetadata('en-US')?.range.maximumSupported.cardinal; // verified inclusive ceiling",
    "LOCALE_MANIFEST['zh-CN'].capabilities.formal; // true",
    '```',
    '',
    '`to-words/manifest` is an opt-in entry point containing compact generated metadata. It does not load the locale conversion tables, so importing it does not change the conversion hot path or per-locale bundles.',
    '',
    'Locale authors can validate custom configurations without importing the locale registry:',
    '',
    '```ts',
    "import { assertLocaleConfig, deriveLocaleCapabilities, deriveLocaleMetadata } from 'to-words/locale-contract';",
    '',
    "assertLocaleConfig(customLocale.config, 'my-locale');",
    'const capabilities = deriveLocaleCapabilities(customLocale.config);',
    'const metadata = deriveLocaleMetadata(customLocale.config);',
    '```',
    '',
    '## Capability Definitions',
    '',
    '- **Ordinal**: the locale declares an ordinal mapping, suffix, or prefix.',
    '- **Gender**: the locale declares explicit cardinal or ordinal gender forms. A dash means the option has no locale-specific form.',
    '- **Formal**: the locale has an alternate formal/financial configuration.',
    "- **Fraction digits**: supported decimal lengths for `decimalStyle: 'fraction'`. Other lengths fall back to digit-style decimals.",
    '- **Currency decimals**: the default currency precision used for rounding and fractional units.',
    '',
    'Cardinal, currency, and digit-style decimal conversion are part of every locale contract.',
    '',
    '## Numbering and Range Definitions',
    '',
    '- **Base thousand**: every configured large unit is a power of 1,000. This structural family includes locales whose words are commonly described as either short scale or long scale.',
    '- **Indian**: the configuration contains lakh (10^5) and crore (10^7) magnitudes; grouping proceeds 3 digits, then 2 digits.',
    '- **East Asian**: the configuration contains 10^4 and 10^8 magnitudes; grouping proceeds in 4-digit units.',
    '- **Locale-specific**: configured large units do not match one of the structural families above. Inspect `largeUnitExponents` for the exact named powers of ten.',
    '- **Largest named scale**: the largest magnitude with an explicit word in the locale configuration.',
    '- **Maximum verified integer**: the inclusive default ceiling for strict conversion. Cardinal, ordinal, and currency ceilings are exposed separately in the runtime manifest.',
    '',
    "`rangeMode: 'strict'` is the v7 default and rejects values above the applicable verified ceiling with `NumberOutOfRangeError`. Use `rangeMode: 'compose'` to opt into the legacy recursive behavior, which reuses the largest configured scale without claiming that the resulting wording has been independently certified by native speakers.",
    '',
    '## All Locales',
    '',
    ...renderTable(
      [
        'Locale',
        'Numbering system',
        'Largest named scale',
        'Maximum verified integer',
        'Ordinal',
        'Gender',
        'Formal',
        'Fraction digits',
        'Currency decimals',
      ],
      rows,
    ),
    '',
  ].join('\n');
}

function renderManifestData() {
  const lines = [
    '// Generated by scripts/generate-locale-docs.mjs. Do not edit directly.',
    'export type GeneratedLocaleCode =',
    ...entries.map(({ localeCode }, index) => `  | '${localeCode}'${index === entries.length - 1 ? ';' : ''}`),
    '',
    'type CompactInteger = number | string;',
    '',
    'type LocaleCapabilityDatum = readonly [',
    '  ordinal: boolean,',
    '  formal: boolean,',
    '  cardinalGender: boolean,',
    '  ordinalGender: boolean,',
    '  fractionDigits: readonly number[],',
    '  currencyPrecision: number,',
    "  numberingSystem: 'base-thousand' | 'indian' | 'east-asian' | 'locale-specific',",
    '  grouping: readonly number[],',
    '  largeUnitExponents: readonly number[],',
    '  largestNamedMagnitude: string,',
    '  largestNamedMagnitudeExponent: number | null,',
    '  maximumSupported:',
    '    | CompactInteger',
    '    | readonly [cardinal: CompactInteger, ordinal: CompactInteger, currency: CompactInteger],',
    '];',
    '',
    'export const LOCALE_CAPABILITY_DATA: Readonly<Record<GeneratedLocaleCode, LocaleCapabilityDatum>> = {',
  ];

  for (const { localeCode, capabilities, metadata } of entries) {
    const maximumValues = [
      metadata.range.maximumSupported.cardinal,
      metadata.range.maximumSupported.ordinal,
      metadata.range.maximumSupported.currency,
    ];
    const compactInteger = (value) => (/^9+$/.test(value) ? String(value.length) : `'${value}'`);
    const maximumSupported = maximumValues.every((value) => value === maximumValues[0])
      ? compactInteger(maximumValues[0])
      : `[${maximumValues.map(compactInteger).join(', ')}]`;
    const values = [
      capabilities.ordinal,
      capabilities.formal,
      capabilities.gender.cardinal,
      capabilities.gender.ordinal,
      `[${capabilities.decimals.fractionDigits.join(', ')}]`,
      capabilities.currencyPrecision,
      `'${metadata.numbering.system}'`,
      `[${metadata.numbering.grouping.join(', ')}]`,
      `[${metadata.numbering.largeUnitExponents.join(', ')}]`,
      `'${metadata.range.largestNamedMagnitude}'`,
      String(metadata.range.largestNamedMagnitudeExponent),
      maximumSupported,
    ].map(String);
    const compactLine = `  '${localeCode}': [${values.join(', ')}],`;

    if (compactLine.length <= 120) {
      lines.push(compactLine);
    } else {
      lines.push(`  '${localeCode}': [`, ...values.map((value) => `    ${value},`), '  ],');
    }
  }

  lines.push('};', '');
  return lines.join('\n');
}

const expected = renderDocument();
const expectedData = renderManifestData();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  const currentData = fs.existsSync(dataOutputPath) ? fs.readFileSync(dataOutputPath, 'utf8') : '';
  if (current !== expected || currentData !== expectedData) {
    console.error('Generated locale artifacts are stale. Run `npm run docs:generate`.');
    process.exitCode = 1;
  } else {
    console.log('Generated locale artifacts are up to date.');
  }
} else {
  fs.writeFileSync(outputPath, expected);
  fs.writeFileSync(dataOutputPath, expectedData);
  console.log(
    `Generated ${path.relative(repositoryRoot, outputPath)} and ${path.relative(repositoryRoot, dataOutputPath)}.`,
  );
}
